/// The declared schema of each database, recorded next to its version.
///
/// An existing file is brought to the declared schema only when its
/// `user_version` differs from the class's `currentSchemaVersion`. A table
/// class that changes without a version bump therefore reaches new installs
/// and no existing one, and nothing else notices: fresh-database tests pass.
/// This test is what notices. It compares what the classes declare with the
/// dump recorded in `test/fixtures/schema/current_*.sql` and fails when they
/// differ, saying whether the version still has to move.
///
/// After a deliberate schema change: bump the version, then record the dump
/// with
///
///     UPDATE_SCHEMA_DUMP=1 fvm dart test --concurrency=2 test/declared_schema_dump_test.dart
///
/// and read the diff of the `.sql` file before committing it: it is the
/// change every existing install will make to its file.
void main() {
  final update = Platform.environment['UPDATE_SCHEMA_DUMP'] == '1';

  void check({
    required String name,
    required String versionConstant,
    required int version,
    required Future<SchemaSnapshot> Function() declared,
  }) {
    test('the $name schema is the one recorded for its version', () async {
      final schema = (await declared()).without(
        ConvergedDatabase.extensionTables,
      );
      final dump = _dump(name: name, version: version, schema: schema);
      final file = File('test/fixtures/schema/current_$name.sql');
      if (update) {
        file.writeAsStringSync(dump);
        return;
      }
      if (!file.existsSync()) {
        fail('${file.path} is missing. Record it with $_recordCommand');
      }
      final recorded = file.readAsStringSync();
      if (recorded == dump) {
        return;
      }
      final recordedVersion = _recordedVersion(recorded);
      final changed = _firstDifferences(recorded, dump);
      if (recordedVersion == version) {
        fail(
          'The declared $name schema changed, and $versionConstant is still '
          '$version.\n'
          'An existing file converges only when its version differs, so '
          'installs would keep the old schema.\n'
          'Bump $versionConstant, then record the dump with '
          '$_recordCommand\n\n$changed',
        );
      }
      fail(
        '${file.path} records version $recordedVersion, $versionConstant is '
        '$version.\nRecord the dump with $_recordCommand\n\n$changed',
      );
    });
  }

  check(
    name: 'workspace',
    versionConstant: 'WorkspaceDatabase.currentSchemaVersion',
    version: WorkspaceDatabase.currentSchemaVersion,
    declared: WorkspaceDatabase.declaredSchema,
  );
  check(
    name: 'global',
    versionConstant: 'GlobalDatabase.currentSchemaVersion',
    version: GlobalDatabase.currentSchemaVersion,
    declared: GlobalDatabase.declaredSchema,
  );
  check(
    name: 'code_index',
    versionConstant: 'CodeIndexDatabase.currentSchemaVersion',
    version: CodeIndexDatabase.currentSchemaVersion,
    declared: CodeIndexDatabase.declaredSchema,
  );
}

const _recordCommand =
    '`UPDATE_SCHEMA_DUMP=1 fvm dart test --concurrency=2 '
    'test/declared_schema_dump_test.dart` (from packages/cc_persistence).';

const _versionPrefix = '-- schema version: ';

int? _recordedVersion(String recorded) {
  for (final line in recorded.split('\n')) {
    if (line.startsWith(_versionPrefix)) {
      return int.tryParse(line.substring(_versionPrefix.length).trim());
    }
  }
  return null;
}

/// The schema as text: one block per table (its statement, one column or
/// constraint per line, then its indexes and triggers by name), tables by
/// name. Shadow tables of virtual tables and automatic indexes are SQLite's
/// and are left out.
String _dump({
  required String name,
  required int version,
  required SchemaSnapshot schema,
}) {
  final owned = <String, List<SchemaObject>>{};
  final tables = <SchemaObject>[];
  for (final object in schema.objects) {
    if (object.sql == null || schema.isShadowTable(object.name)) {
      continue;
    }
    if (object.type == 'table') {
      tables.add(object);
    } else {
      owned.putIfAbsent(object.table, () => []).add(object);
    }
  }
  tables.sort((a, b) => a.name.compareTo(b.name));
  final out = StringBuffer()
    ..writeln('-- Declared schema of the $name database.')
    ..writeln('-- Generated by test/declared_schema_dump_test.dart: do not edit.')
    ..writeln('$_versionPrefix$version');
  for (final table in tables) {
    out
      ..writeln()
      ..writeln('${_splitColumns(table.normalizedSql)};');
    final rest = (owned.remove(table.name) ?? [])
      ..sort((a, b) {
        final byType = a.type.compareTo(b.type);
        return byType != 0 ? byType : a.name.compareTo(b.name);
      });
    for (final object in rest) {
      out.writeln('${object.normalizedSql};');
    }
  }
  // Objects on a table this schema does not declare (there are none today).
  final strays = owned.values.expand((objects) => objects).toList()
    ..sort((a, b) => a.name.compareTo(b.name));
  for (final object in strays) {
    out
      ..writeln()
      ..writeln('${object.normalizedSql};');
  }
  return out.toString();
}

/// Puts each column and table constraint of a `CREATE TABLE` on its own
/// line, so a changed column is a changed line. Other statements (virtual
/// tables included) stay on one line.
String _splitColumns(String sql) {
  final open = sql.indexOf('(');
  if (!sql.startsWith('CREATE TABLE') || open < 0) {
    return sql;
  }
  final close = sql.lastIndexOf(')');
  final parts = <String>[];
  var depth = 0;
  String? quote;
  var start = open + 1;
  for (var i = open + 1; i < close; i++) {
    final char = sql[i];
    if (quote != null) {
      if (char == quote) {
        quote = null;
      }
    } else if (char == "'" || char == '"' || char == '`') {
      quote = char;
    } else if (char == '(') {
      depth++;
    } else if (char == ')') {
      depth--;
    } else if (char == ',' && depth == 0) {
      parts.add(sql.substring(start, i).trim());
      start = i + 1;
    }
  }
  parts.add(sql.substring(start, close).trim());
  return '${sql.substring(0, open + 1)}\n'
      '${parts.map((part) => '  $part').join(',\n')}\n'
      '${sql.substring(close)}';
}

/// The first lines that differ, for the failure text.
String _firstDifferences(String recorded, String current) {
  final was = recorded.split('\n').toSet();
  final now = current.split('\n').toSet();
  final removed = recorded.split('\n').where((l) => !now.contains(l)).take(12);
  final added = current.split('\n').where((l) => !was.contains(l)).take(12);
  return [
    for (final line in removed) '- $line',
    for (final line in added) '+ $line',
  ].join('\n');
}
